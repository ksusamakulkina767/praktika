using System; 

class Program 
{
    static void Main() 
    {
        // создание вещественного массива из 10 элементов
        double[] array = new double[10]; 

        Random random = new Random(); // создание объекта для генерации случайных чисел

        // заполнение массива случайными числами
        for (int i = 0; i < array.Length; i++) 
        {
            array[i] = random.NextDouble() * 20 - 10; // генерация числа из диапазона от -10 до 10
        }

        // создание массива для хранения индексов
        int[] indexes = new int[10]; 

        // заполнение массива индексами от 0 до 9
        for (int i = 0; i < indexes.Length; i++) // цикл перебора элементов массива индексов
        {
            indexes[i] = i; // запись текущего индекса в массив
        }

        // сортировка индексов по значениям элементов первого массива
        for (int i = 0; i < indexes.Length - 1; i++) // внешний цикл сортировки
        {
            for (int j = 0; j < indexes.Length - 1 - i; j++) // внутренний цикл сравнения элементов
            {
                // сравнение значений элементов первого массива по индексам
                if (array[indexes[j]] > array[indexes[j + 1]]) // проверка условия перестановки индексов
                {
                    int temp = indexes[j]; // временное сохранение первого индекса

                    indexes[j] = indexes[j + 1]; // присваивание первого индекса второму

                    indexes[j + 1] = temp; // присваивание второго индекса первому
                }
            }
        }

        // вывод исходного массива
        Console.WriteLine("Первый массив:"); // вывод заголовка

        for (int i = 0; i < array.Length; i++) // цикл перебора элементов первого массива
        {
            Console.Write($"[{i}] = {array[i]:F2}   "); // вывод индекса и значения элемента
        }

        Console.WriteLine(); // переход на новую строку

        // вывод массива индексов
        Console.WriteLine("\nМассив индексов в порядке возрастания:"); // вывод заголовка
        Console.ReadLine();
        for (int i = 0; i < indexes.Length; i++) // цикл перебора массива индексов
        {
            Console.Write(indexes[i] + " "); // вывод каждого индекса
        }

   

        // вывод элементов первого массива в порядке возрастания
        Console.WriteLine("\nЭлементы в порядке возрастания:"); // вывод заголовка
        Console.ReadLine();

        for (int i = 0; i < indexes.Length; i++) // цикл перебора отсортированных индексов
        {
            Console.Write($"{array[indexes[i]]:F2} "); // вывод значения элемента по соответствующему индексу
        }

        Console.WriteLine(); // переход на новую строку
    }
}

