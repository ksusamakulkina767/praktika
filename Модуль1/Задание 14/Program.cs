using System; 

class Program 
{
    static void Main() 
    {
        int n; 

    
        while (true) 
        {
            Console.Write("Введите размер квадратной матрицы N: "); 

            if (int.TryParse(Console.ReadLine(), out n) && n > 0) // проверка ввода целого положительного числа и сохранение его в n
                break; // выход из цикла при правильном вводе

            Console.WriteLine("Ошибка! N должно быть положительным целым числом."); 
        }

        int[,] matrix = new int[n, n]; // создание квадратной матрицы размером n на n

        Random random = new Random(); // создание генератора случайных чисел

        // заполнение матрицы случайными значениями
        for (int i = 0; i < n; i++) // цикл перебора строк матрицы
        {
            for (int j = 0; j < n; j++) // цикл перебора столбцов матрицы
            {
                matrix[i, j] = random.Next(-50, 51); // присваивание элементу случайного значения от -50 до 50
            }
        }

        Console.WriteLine("\nИсходная матрица:");
        // вывод исходной матрицы
        for (int i = 0; i < n; i++) // цикл перебора строк матрицы
        {
            for (int j = 0; j < n; j++) // цикл перебора элементов текущей строки
            {
                Console.Write($"{matrix[i, j],5}"); // вывод элемента матрицы с отступом в 5 символов
            }

            Console.WriteLine(); 
        }
        for (int i = 0; i < n - 1; i++) // внешний цикл сортировки строк
        {
            for (int k = 0; k < n - 1 - i; k++) // Внутренний цикл сравнения соседних строк
            {
                int sum1 = 0; // объявление переменной для суммы элементов первой строки

                int sum2 = 0; // объявление переменной для суммы элементов следующей строки

            
                for (int j = 0; j < n; j++) // цикл перебора элементов первой строки
                {
                    sum1 += matrix[k, j]; // добавление элемента первой строки к её сумме
                }

         
                for (int j = 0; j < n; j++) // цикл перебора элементов следующей строки
                {
                    sum2 += matrix[k + 1, j]; // добавление элемента следующей строки к её сумме
                }

                if (sum1 > sum2) // проверка превышения суммы первой строки над суммой второй строки
                {
           
                    for (int j = 0; j < n; j++) // цикл перебора элементов двух строк
                    {
                        int temp = matrix[k, j]; // временное сохранение элемента первой строки

                        matrix[k, j] = matrix[k + 1, j]; // присваивание элементу первой строки значения из второй строки

                        matrix[k + 1, j] = temp; // присваивание элементу второй строки сохранённого значения
                    }
                }
            }
        }

        Console.WriteLine("\nМатрица после сортировки строк:"); // вывод заголовка отсортированной матрицы

        for (int i = 0; i < n; i++) // цикл перебора строк отсортированной матрицы
        {
            for (int j = 0; j < n; j++) // цикл перебора элементов текущей строки
            {
                Console.Write($"{matrix[i, j],5}"); // вывод элемента матрицы с отступом в 5 символов
            }

            Console.WriteLine(); 
    }
}
}

